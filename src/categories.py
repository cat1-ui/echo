# -*- coding: utf-8 -*-
"""
Echo 情感陪伴智能体 - 记忆分类定义
=================================================
定义记忆的固定分类体系（7 类），以及每类对应的图标。
供记忆提取（prompt 约束）和界面展示（分组 + 图标）共用。
"""

# 分类顺序（用于界面展示的排序）
CATEGORIES = ["基本信息", "喜好", "目标", "烦恼", "习惯", "重要事件", "其他"]

# 每个分类对应的 emoji 图标
CATEGORY_ICONS = {
    "基本信息": "📋",
    "喜好": "❤️",
    "目标": "🎯",
    "烦恼": "😟",
    "习惯": "🔁",
    "重要事件": "📅",
    "其他": "📌",
}

# 兜底：未知分类的图标
DEFAULT_ICON = "📌"


def get_icon(category):
    """根据分类名返回图标，未知分类用兜底图标"""
    return CATEGORY_ICONS.get(category, DEFAULT_ICON)
